-- Provider configuration is shared by the platform. Family data, proposals,
-- chats and attachments retain their existing archive RLS policies.
CREATE TABLE IF NOT EXISTS platform_ai_settings
  (LIKE ai_settings INCLUDING DEFAULTS INCLUDING CONSTRAINTS);
ALTER TABLE platform_ai_settings DROP COLUMN IF EXISTS archive_id;
CREATE UNIQUE INDEX IF NOT EXISTS platform_ai_settings_singleton ON platform_ai_settings(id);

-- A deleted tree must not reset an account's current daily allowance.
-- These are internal billing counters, not a second copy of chat content.
CREATE TABLE IF NOT EXISTS platform_ai_usage (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  archive_id text NOT NULL DEFAULT current_setting('drevo.archive_id',true),
  source_usage_id bigint,
  at text NOT NULL,
  started_ms bigint NOT NULL,
  user_id text NOT NULL,
  model text NOT NULL,
  status text NOT NULL CHECK(status IN ('ok','error')),
  provider_calls bigint NOT NULL,
  input_tokens bigint NOT NULL,
  output_tokens bigint NOT NULL,
  total_tokens bigint NOT NULL,
  latency_ms bigint NOT NULL,
  cached_input_tokens bigint NOT NULL DEFAULT 0,
  UNIQUE(archive_id,source_usage_id)
);
CREATE INDEX IF NOT EXISTS platform_ai_usage_user_started
  ON platform_ai_usage(user_id,started_ms DESC);
CREATE INDEX IF NOT EXISTS platform_ai_usage_started ON platform_ai_usage(started_ms DESC);
CREATE TABLE IF NOT EXISTS platform_ai_usage_models (
  usage_id bigint NOT NULL REFERENCES platform_ai_usage(id) ON DELETE CASCADE,
  model text NOT NULL,
  provider_calls bigint NOT NULL,
  input_tokens bigint NOT NULL,
  output_tokens bigint NOT NULL,
  total_tokens bigint NOT NULL,
  PRIMARY KEY(usage_id,model)
);
CREATE INDEX IF NOT EXISTS platform_ai_usage_models_model
  ON platform_ai_usage_models(model,usage_id);
