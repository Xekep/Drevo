-- Runtime service tables. Every archive-owned row is protected by forced RLS.
-- Run as the migration role, never automatically from a web request.

CREATE TABLE IF NOT EXISTS share_links (
  archive_id text NOT NULL DEFAULT current_setting('drevo.archive_id', true) REFERENCES archives(id) ON DELETE CASCADE,
  id TEXT NOT NULL,
  token_hash TEXT  NOT NULL,
  title TEXT NOT NULL,
  anchor_id TEXT NOT NULL,
  person_ids jsonb NOT NULL,
  created_at TEXT NOT NULL,
  expires_at TEXT NOT NULL,
  created_by TEXT NOT NULL,
  created_name TEXT NOT NULL,
  revoked_at TEXT
,
  PRIMARY KEY(archive_id,id),
  UNIQUE(archive_id,token_hash));

CREATE TABLE IF NOT EXISTS share_link_activity (
  archive_id text NOT NULL DEFAULT current_setting('drevo.archive_id', true),
  share_id text NOT NULL,
  last_visited_at text NOT NULL,
  PRIMARY KEY (archive_id, share_id),
  FOREIGN KEY (archive_id, share_id)
    REFERENCES share_links(archive_id, id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS geocode_cache (
  archive_id text NOT NULL DEFAULT current_setting('drevo.archive_id', true) REFERENCES archives(id) ON DELETE CASCADE,
  query TEXT NOT NULL,
  data TEXT NOT NULL,
  saved_at bigint NOT NULL
,
  PRIMARY KEY(archive_id,query));

CREATE TABLE IF NOT EXISTS migrations (
  archive_id text NOT NULL DEFAULT current_setting('drevo.archive_id', true) REFERENCES archives(id) ON DELETE CASCADE,
  id TEXT NOT NULL
,
  PRIMARY KEY(archive_id,id));

CREATE TABLE IF NOT EXISTS face_descriptors (
  archive_id text NOT NULL DEFAULT current_setting('drevo.archive_id', true) REFERENCES archives(id) ON DELETE CASCADE,
        id TEXT NOT NULL,
        person_id TEXT NOT NULL,
        data jsonb NOT NULL,
        created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
      , source_tag_id TEXT, created_by TEXT, source_photo_id TEXT, model TEXT NOT NULL DEFAULT 'face-api-1.7.15',
  PRIMARY KEY(archive_id,id),
  FOREIGN KEY(archive_id,person_id) REFERENCES people(archive_id,id) ON DELETE CASCADE,
  FOREIGN KEY(archive_id,source_tag_id) REFERENCES photo_tags(archive_id,id) ON DELETE CASCADE,
  FOREIGN KEY(archive_id,source_photo_id) REFERENCES photos(archive_id,id) ON DELETE CASCADE);

CREATE TABLE IF NOT EXISTS mcp_tokens (
  archive_id text NOT NULL DEFAULT current_setting('drevo.archive_id', true) REFERENCES archives(id) ON DELETE CASCADE,
        id TEXT NOT NULL,
        token_hash TEXT  NOT NULL,
        token_hint TEXT NOT NULL,
        name TEXT NOT NULL,
        scopes jsonb NOT NULL,
        created_at TEXT NOT NULL,
        expires_at bigint,
        created_by TEXT NOT NULL,
        revoked_at TEXT,
        last_used_at bigint
      , rate_limit_per_minute bigint NOT NULL DEFAULT 60
          CHECK(rate_limit_per_minute BETWEEN 0 AND 600), bound_user_id TEXT,
  PRIMARY KEY(archive_id,id),
  UNIQUE(archive_id,token_hash),
  FOREIGN KEY(archive_id,bound_user_id) REFERENCES archive_memberships(archive_id,user_id) ON DELETE CASCADE);

CREATE TABLE IF NOT EXISTS ai_settings (
  archive_id text NOT NULL DEFAULT current_setting('drevo.archive_id', true) REFERENCES archives(id) ON DELETE CASCADE,
        id bigint NOT NULL CHECK(id=1),
        enabled bigint NOT NULL DEFAULT 1 CHECK(enabled IN (0,1)),
        model TEXT NOT NULL DEFAULT ''
      , requests_per_minute bigint NOT NULL DEFAULT 6
          CHECK(requests_per_minute BETWEEN 0 AND 120), daily_requests bigint NOT NULL DEFAULT 100
          CHECK(daily_requests BETWEEN 0 AND 100000), daily_tokens bigint NOT NULL DEFAULT 250000
          CHECK(daily_tokens BETWEEN 0 AND 1000000000), api_key_ciphertext TEXT NOT NULL DEFAULT '', folder_id TEXT NOT NULL DEFAULT '', compaction_enabled bigint NOT NULL DEFAULT 1 CHECK(compaction_enabled IN (0,1)), compact_threshold_tokens bigint NOT NULL DEFAULT 32000 CHECK(compact_threshold_tokens BETWEEN 1000 AND 1000000), automatic_truncation bigint NOT NULL DEFAULT 1 CHECK(automatic_truncation IN (0,1)), max_tool_iterations bigint NOT NULL DEFAULT 8 CHECK(max_tool_iterations BETWEEN 1 AND 20), web_search_enabled bigint CHECK(web_search_enabled IS NULL OR web_search_enabled IN (0,1)),
  PRIMARY KEY(archive_id,id));

CREATE TABLE IF NOT EXISTS ai_usage (
  archive_id text NOT NULL DEFAULT current_setting('drevo.archive_id', true) REFERENCES archives(id) ON DELETE CASCADE,
        id bigint GENERATED BY DEFAULT AS IDENTITY,
        at TEXT NOT NULL,
        started_ms bigint NOT NULL,
        user_id TEXT NOT NULL,
        model TEXT NOT NULL,
        status TEXT NOT NULL CHECK(status IN ('ok','error')),
        provider_calls bigint NOT NULL,
        input_tokens bigint NOT NULL,
        output_tokens bigint NOT NULL,
        total_tokens bigint NOT NULL,
        latency_ms bigint NOT NULL
      , cached_input_tokens bigint NOT NULL DEFAULT 0,
  PRIMARY KEY(archive_id,id));

CREATE TABLE IF NOT EXISTS mcp_usage (
  archive_id text NOT NULL DEFAULT current_setting('drevo.archive_id', true) REFERENCES archives(id) ON DELETE CASCADE,
        id bigint GENERATED BY DEFAULT AS IDENTITY,
        at TEXT NOT NULL,
        started_ms bigint NOT NULL,
        token_id TEXT NOT NULL,
        method TEXT NOT NULL,
