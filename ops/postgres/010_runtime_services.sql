 SELECT 1 AS id,public_tree::integer AS public_tree,public_albums::integer AS public_albums FROM archive_access_settings;
CREATE OR REPLACE VIEW runtime_tree_settings WITH (security_invoker=true) AS
 SELECT 1 AS id,reverse_timeline::integer AS reverse_timeline FROM archive_tree_settings;
