CREATE OR REPLACE FUNCTION runtime_tag_changed() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 UPDATE face_descriptors SET person_id=NEW.person_id,source_photo_id=NEW.photo_id
 WHERE archive_id=NEW.archive_id AND source_tag_id=NEW.id;
 RETURN NEW;
END $$;
DROP TRIGGER IF EXISTS runtime_tag_changed ON photo_tags;
CREATE TRIGGER runtime_tag_changed AFTER UPDATE OF person_id,photo_id ON photo_tags
 FOR EACH ROW EXECUTE FUNCTION runtime_tag_changed();
CREATE OR REPLACE FUNCTION runtime_member_deleted() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 DELETE FROM ai_chats WHERE archive_id=OLD.archive_id AND user_id=OLD.user_id;
 DELETE FROM account_sessions WHERE user_id=OLD.user_id;
 RETURN OLD;
END $$;
DROP TRIGGER IF EXISTS runtime_member_deleted ON archive_memberships;
CREATE TRIGGER runtime_member_deleted AFTER DELETE ON archive_memberships
 FOR EACH ROW EXECUTE FUNCTION runtime_member_deleted();
