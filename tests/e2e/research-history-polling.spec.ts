import { expect, test } from "@playwright/test";

test("assistant opens latest history on demand, loads older pages and polls small version deltas", async ({ page }) => {
  await page.clock.install();
  const id = "7569f80b-399c-4977-b877-bd504b49feac";
  let version = 110, busy = false, initialReads = 0, deltaReads = 0, olderReads = 0;
  let changed = { id: 50, version: 111, role: "assistant", content: "Ответ обновлён в другой вкладке" };
  const messages = Array.from({ length: 110 }, (_, index) => ({ id: index + 1, version: index + 1, role: "assistant", content: `Ответ ${index + 1}` }));
  await page.route("**/api/ai/status", route => route.fulfill({ json: { enabled: true, streaming: true } }));
  await page.route("**/api/research/suggestions", route => route.fulfill({ json: { suggestions: [] } }));
  await page.route("**/api/ai/chats", route => route.fulfill({ json: { chats: [{ id, title: "История", updatedAt: "2026-10-12T12:00:00Z" }] } }));
  await page.route(`**/api/ai/chats/${id}*`, async route => {
    const params = new URL(route.request().url()).searchParams;
    const before = Number(params.get("before") || 0);
    const cursor = params.has("version") ? Number(params.get("version")) : null;
    const pageMessages = before ? messages.filter(message => message.id < before) : cursor === null ? messages.slice(-100) : cursor < version ? [changed] : [];
    if (before) olderReads++; else if (cursor !== null) deltaReads++; else initialReads++;
    await route.fulfill({ json: { chat: { id, busy, createdAt: "2026-10-12T12:00:00Z", updatedAt: "2026-10-12T12:00:00Z", lastMessageId: 110 }, messages: pageMessages, latestMessageId: 110, latestVersion: version, nextBefore: before || cursor !== null ? null : 11, hasMore: cursor === null && !before } });
  });
  await page.goto("/tree");
  await expect(page.getByRole("button", { name: "Открыть ИИ-исследователя" })).toBeVisible();
  expect(initialReads).toBe(0);
  await page.getByRole("button", { name: "Открыть ИИ-исследователя" }).click();
  const panel = page.locator(".research-assistant");
  await expect(panel.locator("article.is-assistant")).toHaveCount(100);
  await expect.poll(() => deltaReads).toBeGreaterThanOrEqual(1);
  const idleBaseline = deltaReads;
  await page.clock.fastForward(5000);
  expect(deltaReads).toBe(idleBaseline);
  await panel.getByRole("button", { name: "Предыдущие сообщения" }).click();
  await expect(panel.locator("article.is-assistant")).toHaveCount(110);
  expect(olderReads).toBe(1);
  await expect(panel.getByRole("button", { name: "Предыдущие сообщения" })).toHaveCount(0);
  version = 111;
  await page.clock.fastForward(30_100);
  await expect(panel).toContainText("Ответ обновлён в другой вкладке");
  await expect(panel.locator("article.is-assistant")).toHaveCount(110);
  expect(initialReads).toBe(1);
  busy = true;
  await page.clock.fastForward(30_100);
  await expect(panel.getByRole("button", { name: "Остановить ответ" })).toBeVisible();
  const busyBaseline = deltaReads;
  await page.clock.fastForward(2100);
  await expect.poll(() => deltaReads).toBeGreaterThan(busyBaseline);
  busy = false;
  changed = { ...changed, version: 112, content: "Завершено" };
  version = 112;
  await page.clock.fastForward(2100);
  await expect(panel).toContainText("Завершено");
  await panel.getByRole("button", { name: "Закрыть ИИ-исследователя" }).click();
  const closedBaseline = deltaReads;
  await page.clock.fastForward(60_100);
  expect(deltaReads).toBe(closedBaseline);
});
